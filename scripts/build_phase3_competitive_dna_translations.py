def _strip_quotes(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        return s[1:-1]
    return s


def _ko_r(type_idx: int, field: str) -> str:
    data = KO_RESULTS[type_idx + 1]
    key_map = {
        "title": "title_ko",
        "competitiveDna": "competitive_dna",
        "quote": "quote",
        "description": "description",
        "competitiveType": "competitive_type",
        "competitiveKeywords": "competitive_keywords",
        "strengths": "strengths",
        "cautions": "cautions",
        "bestEnvironments": "best_environments",
        "sportsGameTypes": "sports_game_types",
        "certificationPhrase": "certification",
        "oneLiner": "one_liner",
        "shareLine": "share_line",
    }
    if field not in key_map:
        raise KeyError(field)
    val = data.get(key_map[field], "")
    if field == "oneLiner":
        return _strip_quotes(val)
    return val


