export function calculatePhase3ExLingeringFeelingsResult(answers: number[]): string {
  const total = answers.reduce((sum, s) => sum + (s ?? 0), 0);
  if (total <= 5) return 'Type1';
  if (total <= 11) return 'Type2';
  if (total <= 19) return 'Type3';
  if (total <= 27) return 'Type4';
  if (total <= 33) return 'Type5';
  return 'Type6';
}

export function getPhase3ExLingeringFeelingsResultByType(
  type: string
): Phase3ExLingeringFeelingsResult | undefined {
  return phase3ExLingeringFeelingsResults.find((r) => r.type === type);
}

