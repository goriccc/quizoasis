export function calculatePhase3OfficeBalanceGameResult(answers: number[]): string {
  const total = answers.reduce((sum, s) => sum + (s ?? 0), 0);
  if (total <= 1) return 'Type1';
  if (total <= 3) return 'Type2';
  if (total <= 5) return 'Type3';
  if (total <= 7) return 'Type4';
  if (total <= 9) return 'Type5';
  return 'Type6';
}

