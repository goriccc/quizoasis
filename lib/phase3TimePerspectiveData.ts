  const emotion = (answers[2] ?? 0) + (answers[3] ?? 0);
  const decision = (answers[4] ?? 0) + (answers[5] ?? 0);
  const happiness = (answers[6] ?? 0) + (answers[7] ?? 0);
  const difficulty = (answers[8] ?? 0) + (answers[9] ?? 0);
  const timeAttitude = (answers[10] ?? 0) + (answers[11] ?? 0);
